export const FONT = {};
for (const [k, v] of Object.entries(G)) FONT[k] = v.padEnd(15, '.').slice(0, 15);

export function textWidth(s) { return s.length * 4 - 1; }

export function drawText(ctx, s, x, y, color, scale = 1) {
  ctx.fillStyle = color;
  s = String(s).toUpperCase();
  for (let i = 0; i < s.length; i++) {
    const g = FONT[s[i]] || FONT['?'];
    for (let r = 0; r < 5; r++) for (let c = 0; c < 3; c++) {
      if (g[r * 3 + c] === '#') ctx.fillRect(x + (i * 4 + c) * scale, y + r * scale, scale, scale);
    }
  }
}
