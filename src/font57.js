// Pre-split into lists of lit pixel coordinates.
export const FONT57 = {};
for (const [ch, rows] of Object.entries(RAW)) {
  const px = [];
  rows.forEach((row, y) => { for (let x = 0; x < 5; x++) if (row[x] === '#') px.push([x, y]); });
  FONT57[ch] = px;
}

